import fs from 'node:fs';
import zlib from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const enable1Path = path.join(__dirname, 'enable1.txt');
const manifestPath = path.join(__dirname, '..', 'client', 'src', 'data', 'words.json');
const outputPath = path.join(__dirname, '..', 'client', 'src', 'data', 'dictionary-data.js');

const enable1Text = fs.readFileSync(enable1Path, 'utf8');
const enable1Words = enable1Text.trim().split(/\r?\n/);

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

const wordsSet = new Set();

for (const w of enable1Words) {
  const clean = w.trim().toUpperCase();
  if (/^[A-Z]{3,12}$/.test(clean)) {
    wordsSet.add(clean);
  }
}

for (const item of manifest.words) {
  const clean = item.word.trim().toUpperCase();
  if (/^[A-Z]{3,12}$/.test(clean)) {
    wordsSet.add(clean);
  }
}

const sorted = Array.from(wordsSet).sort();
const text = sorted.join('\n');

const jsCode = `// Generated by tools/build-dictionary.js — DO NOT EDIT DIRECTLY\n// Source: ENABLE1 (Public Domain) + locked manifest words (lengths 3–12)\nexport const DICTIONARY_TEXT = ${JSON.stringify(text)};\n`;

fs.writeFileSync(outputPath, jsCode, 'utf8');

const compressed = zlib.gzipSync(Buffer.from(jsCode));
console.log(`Generated ${outputPath}`);
console.log(`Total words: ${sorted.length}`);
console.log(`Raw size: ${(jsCode.length / 1024).toFixed(1)} KB`);
console.log(`Gzip size: ${(compressed.length / 1024).toFixed(1)} KB`);
